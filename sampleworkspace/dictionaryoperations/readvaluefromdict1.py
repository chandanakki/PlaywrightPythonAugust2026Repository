# Case 4: How to Read Value from Dictionary.
customers ={
    "customername":"Lenovo Services",
    "emailid":"services@lenovo.com",
    "location":"Bangalore",
    "feeback":"Positive"
}

# Read a Value
print(customers["customername"])
print(customers["emailid"])
print(customers["location"])
print(customers["feeback"])

# Read in a single print statement
print(customers["customername"], customers["emailid"], customers["location"], customers["feeback"])