# Inbuilt Functions
# count: It provides count of  element 
elements= ("Mango",100,True,10.175,False,"Lotus","Sunflower","Orange","Sparrow","Mango","Mango")
print(elements.count("Mango"))  # 3
print(elements.count("Orange"))  # 1
print("------------------")
# index : It provides index or position of the Element in tuple.
print(elements.index("Lotus"))  # 6
print(elements.index(True))  # 2