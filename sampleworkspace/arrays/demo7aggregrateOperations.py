#Case 4: Apply Aggregate operations:
import numpy as np
 
arr=np.array([50,90,10,30,20,40,70])
# Aggregate Operations
print("Sum of All Elements :",arr.sum())
print("Max of All Elements :",arr.max())
print("Min of All Elements :",arr.min())
print("Count of All Elements :",arr.size)
print("Mean of All Elements :",arr.mean())